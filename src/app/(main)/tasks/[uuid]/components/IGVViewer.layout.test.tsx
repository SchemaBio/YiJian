import * as React from 'react';
import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {render,screen,fireEvent,waitFor} from '@testing-library/react';
import igv from 'igv/dist/igv.esm.js';
import {IGVViewer} from './IGVViewer';
import type {IGVSession} from '../types';
vi.mock('igv/dist/igv.esm.js',()=>({default:{createBrowser:vi.fn(),removeBrowser:vi.fn()}}));
vi.mock('../result-api',()=>({getIGVSession:vi.fn(),getIGVTrackURLs:vi.fn(),getIGVSnapshot:vi.fn(async()=>({available:false})),saveIGVSnapshot:vi.fn()}));
vi.mock('@/lib/igv-snapshot',()=>({igvSVGToPNG:vi.fn()}));
const session:IGVSession={taskUuid:'fixture',executionAttemptId:'attempt',version:'v',available:true,reference:{available:true,id:'hg19',fastaURL:'/reference',indexURL:'/index'},tracks:['proband','father','mother'].map(id=>({id,name:id,type:'alignment',format:'bam',hasIndex:true,available:true}))};
let available=720;
beforeEach(()=>{available=720;vi.clearAllMocks();});
afterEach(()=>vi.restoreAllMocks());
it('removes both modal height constraints and fits three reads viewports when expanded, then restores them',async()=>{
 const views=Array.from({length:3},()=>{const view={track:{type:'alignment',height:180,autoHeight:false,coverageTrackHeight:50},setTrackHeight:vi.fn((height:number)=>{view.track.height=height;})};return view;});
 let content:HTMLElement|undefined;
 const browser={trackViews:views,search:vi.fn().mockResolvedValue(undefined),loadTrack:vi.fn().mockResolvedValue({}),dispose:vi.fn(),toSVG:vi.fn(),removeTrackByName:vi.fn(),updateViews:vi.fn().mockResolvedValue(undefined),currentLoci:vi.fn().mockReturnValue('chr1:1-110')};
 vi.mocked(igv.createBrowser).mockImplementation(async element=>{content=element;return browser;});
 const rectangle=HTMLElement.prototype.getBoundingClientRect;
 vi.spyOn(HTMLElement.prototype,'getBoundingClientRect').mockImplementation(function(this:HTMLElement){if(this===content)return {...rectangle.call(this),height:90+views.reduce((sum,v)=>sum+v.track.height,0)};return rectangle.call(this);});
 vi.spyOn(HTMLElement.prototype,'clientHeight','get').mockImplementation(function(this:HTMLElement){return this.hasAttribute('data-igv-viewport')?available:0;});
 const view=render(<IGVViewer taskId="fixture" chromosome="1" position={10} isOpen onClose={vi.fn()} session={session}/>);
 await waitFor(()=>expect(browser.loadTrack).toHaveBeenCalledTimes(3));
 const expand=screen.getByRole('button',{name:'放大'}),close=screen.getByRole('button',{name:'关闭弹窗'});
 expect(expand.nextElementSibling).toBe(close);fireEvent.click(expand);
 const dialog=screen.getByRole('dialog');expect(dialog).toHaveClass('!flex','!flex-col','!h-[100dvh]');
 const viewport=document.querySelector('[data-igv-viewport]')!;expect(viewport.parentElement).toHaveClass('!max-h-none','!overflow-hidden','!flex-1');
 await waitFor(()=>expect(views.every(v=>v.track.height>180)).toBe(true));
 expect(90+views.reduce((sum,v)=>sum+v.track.height,0)).toBeLessThanOrEqual(available);
 available=420;fireEvent(window,new Event('resize'));
 await waitFor(()=>expect(views.every(v=>v.track.height<180)).toBe(true));expect(90+views.reduce((sum,v)=>sum+v.track.height,0)).toBeLessThanOrEqual(available);
 fireEvent.click(screen.getByRole('button',{name:'缩小'}));await waitFor(()=>expect(views.every(v=>v.track.height===180&&v.track.coverageTrackHeight===50)).toBe(true));
 expect(igv.createBrowser).toHaveBeenCalledTimes(1);expect(igv.removeBrowser).not.toHaveBeenCalled();view.unmount();
});
